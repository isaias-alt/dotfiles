#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
SOURCE="${SYNC_AGENTS_SOURCE:-$SCRIPT_DIR/home/AGENTS.md}"
OPEN_MARKER="<!-- dotfiles:global -->"
CLOSE_MARKER="<!-- /dotfiles:global -->"

if [[ ! -f "$SOURCE" || ! -s "$SOURCE" ]]; then
  printf 'ERROR: source rules file not found or empty: %s\n' "$SOURCE" >&2
  exit 1
fi

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

resolve_path() {
  local target="$1"
  local hops=0 dir link
  while [[ -L "$target" ]]; do
    hops=$((hops + 1))
    ((hops > 16)) && return 1
    dir="$(cd -P "$(dirname "$target")" 2>/dev/null && pwd -P)" || return 1
    link="$(readlink "$target")"
    if [[ "$link" == /* ]]; then
      target="$link"
    else
      target="$dir/$link"
    fi
  done
  [[ -e "$target" ]] || return 1
  dir="$(cd -P "$(dirname "$target")" 2>/dev/null && pwd -P)" || return 1
  printf '%s/%s\n' "$dir" "$(basename "$target")"
}

emit_block() {
  local payload="$1"
  printf '%s\n' "$OPEN_MARKER"
  cat "$payload"
  if [[ -s "$payload" ]] && [[ -n "$(tail -c 1 "$payload")" ]]; then
    printf '\n'
  fi
  printf '%s\n' "$CLOSE_MARKER"
}

write_atomic() {
  local target="$1" content_file="$2" label="$3"
  local dir tmp
  dir="$(dirname "$target")"
  mkdir -p "$dir"

  if [[ -L "$target" ]]; then
    printf 'ERROR: %s (%s) is a symlink; refusing to overwrite\n' "$label" "$target" >&2
    return 1
  fi

  if [[ -d "$target" ]]; then
    printf 'ERROR: %s (%s) is a directory; refusing to overwrite\n' "$label" "$target" >&2
    return 1
  fi

  if [[ -f "$target" ]] && cmp -s "$target" "$content_file"; then
    printf 'ok      %s (%s)\n' "$label" "$target"
    return 0
  fi

  if [[ -f "$target" && ! -w "$target" ]]; then
    printf 'ERROR: %s (%s) is not writable\n' "$label" "$target" >&2
    return 1
  fi

  tmp="$(mktemp "$dir/.sync-agents.XXXXXX")"
  if [[ -f "$target" ]]; then
    cp -p "$target" "$tmp" || {
      rm -f "$tmp"
      return 1
    }
  fi
  cat "$content_file" >"$tmp" || {
    rm -f "$tmp"
    return 1
  }
  mv -f "$tmp" "$target" || {
    rm -f "$tmp"
    return 1
  }
  printf 'updated %s (%s)\n' "$label" "$target"
}

sync_marked_file() {
  local target="$1" payload="$2" label="$3"
  local out="$WORK_DIR/rendered.md"

  if [[ -L "$target" ]]; then
    printf 'ERROR: %s (%s) is a symlink; refusing to overwrite\n' "$label" "$target" >&2
    return 1
  fi

  if [[ -d "$target" ]]; then
    printf 'ERROR: %s (%s) is a directory; refusing to overwrite\n' "$label" "$target" >&2
    return 1
  fi

  if [[ ! -s "$target" ]]; then
    emit_block "$payload" >"$out"
    write_atomic "$target" "$out" "$label"
    return $?
  fi

  local in_block=0 seen_block=0 line="" trimmed="" last_line=""
  : >"$out"

  while IFS= read -r line || [[ -n "$line" ]]; do
    trimmed="${line%$'\r'}"
    if [[ "$trimmed" == "$OPEN_MARKER" ]]; then
      if ((in_block == 1)); then
        printf 'ERROR: %s (%s) has nested/unclosed %s marker\n' "$label" "$target" "$OPEN_MARKER" >&2
        return 1
      fi
      in_block=1
      if ((seen_block == 0)); then
        emit_block "$payload" >>"$out"
        seen_block=1
      fi
    elif [[ "$trimmed" == "$CLOSE_MARKER" ]]; then
      if ((in_block == 0)); then
        printf 'ERROR: %s (%s) has orphan %s marker\n' "$label" "$target" "$CLOSE_MARKER" >&2
        return 1
      fi
      in_block=0
    elif ((in_block == 0)); then
      printf '%s\n' "$line" >>"$out"
      last_line="$trimmed"
    fi
  done <"$target"

  if ((in_block == 1)); then
    printf 'ERROR: %s (%s) has unclosed %s marker\n' "$label" "$target" "$OPEN_MARKER" >&2
    return 1
  fi

  if ((seen_block == 0)); then
    if [[ -n "$last_line" ]]; then
      printf '\n' >>"$out"
    fi
    emit_block "$payload" >>"$out"
  fi

  write_atomic "$target" "$out" "$label"
}

status=0

# Claude Code (preserves gentle-ai marker blocks in ~/.claude/CLAUDE.md)
if [[ -d "$HOME/.claude" ]]; then
  sync_marked_file "$HOME/.claude/CLAUDE.md" "$SOURCE" "claude-code" || status=1
fi

# OpenCode (preserves gentle-ai marker blocks in ~/.config/opencode/AGENTS.md)
if [[ -d "$HOME/.config/opencode" ]]; then
  sync_marked_file "$HOME/.config/opencode/AGENTS.md" "$SOURCE" "opencode" || status=1
fi

# Codex (preserves gentle-ai marker blocks in $CODEX_HOME/AGENTS.md or ~/.codex/AGENTS.md)
CODEX_DIR="${CODEX_HOME:-$HOME/.codex}"
if [[ -d "$CODEX_DIR" ]]; then
  sync_marked_file "$CODEX_DIR/AGENTS.md" "$SOURCE" "codex" || status=1
fi

# Antigravity (standalone rule outside gentle-ai-NN- namespace)
if [[ -d "$HOME/.gemini/config" ]]; then
  AGY_OUT="$WORK_DIR/antigravity.md"
  {
    printf '%s\n' '---'
    printf '%s\n' 'trigger: always_on'
    printf '%s\n' '---'
    printf '\n'
    printf '%s\n\n' '<!-- Generated by dotfiles/sync-agents.sh from home/AGENTS.md. Do not edit directly. -->'
    cat "$SOURCE"
    if [[ -s "$SOURCE" ]] && [[ -n "$(tail -c 1 "$SOURCE")" ]]; then
      printf '\n'
    fi
  } >"$AGY_OUT"
  write_atomic "$HOME/.gemini/config/rules/dotfiles-global.md" "$AGY_OUT" "antigravity" || status=1
fi

# Gemini CLI (import helper file from GEMINI.md so Antigravity does not load full rules twice)
if [[ -f "$HOME/.gemini/GEMINI.md" || -L "$HOME/.gemini/GEMINI.md" || -d "$HOME/.gemini/gentle-ai" ]]; then
  GEMINI_IMPORT="$WORK_DIR/gemini-import.md"
  printf '%s\n' '@./dotfiles-global.md' >"$GEMINI_IMPORT"
  if sync_marked_file "$HOME/.gemini/GEMINI.md" "$GEMINI_IMPORT" "gemini-cli (import)"; then
    GEMINI_HELPER="$WORK_DIR/gemini-helper.md"
    {
      printf '%s\n\n' '<!-- Generated by dotfiles/sync-agents.sh from home/AGENTS.md. Do not edit directly. -->'
      cat "$SOURCE"
      if [[ -s "$SOURCE" ]] && [[ -n "$(tail -c 1 "$SOURCE")" ]]; then
        printf '\n'
      fi
    } >"$GEMINI_HELPER"
    write_atomic "$HOME/.gemini/dotfiles-global.md" "$GEMINI_HELPER" "gemini-cli (rules)" || status=1
  else
    status=1
  fi
fi

# Pi (home.nix symlinks ~/.pi/agent/AGENTS.md -> home/AGENTS.md; fallback to marked block if regular file)
if [[ -d "$HOME/.pi/agent" ]]; then
  PI_TARGET="$HOME/.pi/agent/AGENTS.md"
  if [[ -L "$PI_TARGET" ]]; then
    SOURCE_REAL="$(resolve_path "$SOURCE" || true)"
    PI_REAL="$(resolve_path "$PI_TARGET" || true)"
    if [[ -n "$SOURCE_REAL" && "$PI_REAL" == "$SOURCE_REAL" ]]; then
      printf 'ok      pi (%s -> %s)\n' "$PI_TARGET" "$SOURCE"
    else
      printf 'warn    pi (%s is a symlink not pointing to %s; run ./rebuild.sh to repoint)\n' "$PI_TARGET" "$SOURCE" >&2
    fi
  else
    sync_marked_file "$PI_TARGET" "$SOURCE" "pi" || status=1
  fi
fi

exit "$status"
